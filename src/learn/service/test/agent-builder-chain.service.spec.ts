/**
 * The chain runs against a fake field generator: each call is logged as
 * start/end events so stage ordering can be asserted from the log, and a
 * per-field override can fail or empty any field on any attempt.
 */

type Responder = (dto: GenerateAgentBuilderFieldDto, attempt: number) => any;

