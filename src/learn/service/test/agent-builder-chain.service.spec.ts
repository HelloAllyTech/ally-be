/**
 * The usage plumbing, through the real ScenarioService method and the real
 * AutofillService, down to the completion request. ScenarioService is built
 * from its prototype: generateAgentBuilderField for a language-agnostic field
 * touches nothing but the autofill service.
 */
describe('ScenarioService.generateAgentBuilderField usage metadata', () => {
  let complete: jest.Mock;
  let autofill: AutofillService;
  let scenarioService: ScenarioService;

  beforeEach(() => {
    complete = jest.fn().mockResolvedValue({
      text: 'You are a client.',
      provider: 'openai',
      model: 'gpt-5-mini',
      source: 'tier',
      usage: {},
    });
    autofill = new AutofillService(
      {
        getPromptByCode: jest
          .fn()
          .mockResolvedValue('Brief: {{actorDescription}}'),
      } as any,
      { complete } as any,
    );
    scenarioService = Object.create(ScenarioService.prototype);
    (scenarioService as any).autofillService = autofill;
  });

  it('records the wizard call exactly as before when no options are given', async () => {
    const spy = jest.spyOn(autofill, 'generateContentFromPrompt');

    const result = await scenarioService.generateAgentBuilderField({
      field: AgentBuilderField.ROLE_INSTRUCTION,
      actorDescription: 'A tired nurse.',
    });

    expect(result).toEqual({
      field: AgentBuilderField.ROLE_INSTRUCTION,
      value: 'You are a client.',
    });
    // Same six arguments the controller path always sent.
    expect(spy.mock.calls[0]).toHaveLength(6);
    expect(complete).toHaveBeenCalledWith(
      expect.objectContaining({
        taskId: 'autofill-agent-field',
        task: LlmTask.AUTOFILL_AGENT_FIELD,
        promptCode: 'agent_builder_role_instruction',
        prompt: 'Brief: A tired nurse.',
      }),
    );
    expect(complete.mock.calls[0][0].usageMetadata).toBeUndefined();
  });

  it('adds the field to the caller metadata on the usage row', async () => {
    await scenarioService.generateAgentBuilderField(
      {
        field: AgentBuilderField.ROLE_INSTRUCTION,
        actorDescription: 'A tired nurse.',
      },
      { usageMetadata: { courseCopilotSessionId: 'session-1' } },
    );

    expect(complete).toHaveBeenCalledWith(
      expect.objectContaining({
        taskId: 'autofill-agent-field',
        task: LlmTask.AUTOFILL_AGENT_FIELD,
        usageMetadata: {
          courseCopilotSessionId: 'session-1',
          field: AgentBuilderField.ROLE_INSTRUCTION,
        },
      }),
    );
  });
});
